function applyLanguage(lang) {
  currentLanguage = lang;
  document.querySelectorAll('[data-page-link]').forEach((link) => {
    const url = new URL(link.getAttribute('href'), window.location.href);
    if (localizedRouteLanguage) url.searchParams.delete('lang');
    else url.searchParams.set('lang', lang);
    link.setAttribute('href', url.pathname.split('/').pop() + url.search + url.hash);
  });
  const pageType = document.body.dataset.page;
  if (pageType === 'gallery') document.title = translations[lang].galleryTitle + ' — Kostanyan Learning Center';
  if (pageType === 'blog') document.title = translations[lang].blogPageTitle;
  if (pageType === 'article-preview') document.title = translations[lang].previewPageTitle;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', translations[lang][el.dataset.i18nAriaLabel]);
  });
  const description = document.querySelector('meta[name="description"]');
  if (description) {
    const descriptionKey = pageType === 'gallery' ? 'galleryIntro' : pageType === 'blog' ? 'blogIntro' : pageType === 'article-preview' ? 'previewLead' : 'footerText';
    description.content = translations[lang][descriptionKey];
  }
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => { el.alt = translations[lang][el.dataset.i18nAlt]; });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key]) el.placeholder = translations[lang][key];
  });
  document.querySelectorAll('[data-ru-href][data-en-href]').forEach((link) => {
    link.setAttribute('href', lang === 'en' ? link.dataset.enHref : link.dataset.ruHref);
  });
  document.querySelectorAll('.lang-button').forEach((button) => {
    button.classList.toggle('is-active', button.dataset.lang === lang);
    button.setAttribute('aria-pressed', String(button.dataset.lang === lang));
  });
  const selectedFormat = document.querySelector('.format-chip.is-selected');
  if (selectedFormat) showFormatDetails(selectedFormat);
  if (status) {
    status.textContent = '';
    status.classList.remove('is-visible');
  }
  validateArmenianPhone();
  document.body.classList.remove('is-localizing');
}

document.querySelectorAll('.lang-button').forEach((button) => {
  button.addEventListener('click', () => {
    const targetLanguage = button.dataset.lang;
    if (!localizedRouteLanguage || !['ru', 'en'].includes(targetLanguage)) {
      applyLanguage(targetLanguage);
      return;
    }

    const explicitTarget = document.body.dataset[`${targetLanguage}Path`];
    if (explicitTarget) {
      window.location.href = `${explicitTarget}${window.location.hash}`;
      return;
    }

    const pageFile = window.location.pathname.split('/').pop() || 'index.html';
    const targetFile = targetLanguage === 'en' && document.body.dataset.enAvailable === 'false'
      ? `translation-unavailable.html?from=${encodeURIComponent(pageFile)}`
      : pageFile;
    window.location.href = `../${targetLanguage}/${targetFile}${window.location.hash}`;
  });
});

if (form && status && submitButton) {
  const setSubmitting = (submitting) => {
    isSubmitting = submitting;
    submitButton.disabled = submitting;
    submitButton.setAttribute('aria-busy', String(submitting));
    submitButton.textContent = translations[currentLanguage][submitting ? 'sending' : 'submit'];
    if (submitting && retryButton) retryButton.hidden = true;
  };

  const showStatus = (message, type) => {
    status.textContent = message;
    status.classList.remove('is-success', 'is-error');
    status.classList.add('is-visible', type === 'error' ? 'is-error' : 'is-success');
  };

  form.addEventListener('submit', async (event) => {
    event.preventDefault();
    if (isSubmitting) return;
    validateArmenianPhone();
    if (!form.checkValidity()) {
      form.reportValidity();
      status.classList.remove('is-visible', 'is-success', 'is-error');
      return;
    }

    const formData = new FormData(form);
    const payload = Object.fromEntries(formData.entries());
    payload.language = currentLanguage;
    setSubmitting(true);

    try {
      const response = await fetch('/api/telegram', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });
      const result = await response.json().catch(() => ({}));
      if (!response.ok || result.ok !== true) {
        const deliveryError = new Error('Delivery failed');
        deliveryError.code = result.code;
        throw deliveryError;
      }

      form.reset();
      if (modeFieldset) {
        modeFieldset.hidden = true;
        modeFieldset.disabled = true;
      }
      modeInputs.forEach((input) => { input.disabled = true; });
      showStatus(translations[currentLanguage].success, 'success');
    } catch (error) {
      const messageKeyByCode = {
        configuration_missing: 'configurationMissing',
        invalid_bot_token: 'invalidBotToken',
        chat_not_found: 'chatNotFound',
        bot_unavailable: 'botUnavailable',
        telegram_unavailable: 'telegramUnavailable',
        invalid_phone: 'invalidArmenianPhone',
      };
      const messageKey = messageKeyByCode[error.code] || 'sendError';
      showStatus(translations[currentLanguage][messageKey], 'error');
      if (retryButton) retryButton.hidden = false;
    } finally {
      setSubmitting(false);
    }
  });

  retryButton?.addEventListener('click', () => form.requestSubmit());
}

